// Phase D.3 — Test authoring & run.
//
// `create_automation_spec` writes a new .cpp Spec file under the project's
// Source/ tree. The file will compile and register a test only after a
// project rebuild — the tool's response makes that explicit.
//
// `run_automation_specs` drives the existing FAutomationTestFramework via the
// "Automation RunTests" console command. Tests are queued and executed by the
// engine's automation controller; results are accumulated in a static buffer
// and returned by `get_last_test_report`.
//
// `add_functional_test_actor` instantiates an AFunctionalTest in the editor
// world; placement-based functional testing is the lighter-weight alternative
// to writing C++ specs.

