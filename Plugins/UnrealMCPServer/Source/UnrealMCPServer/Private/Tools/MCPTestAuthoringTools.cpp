// ---------------------------------------------------------------------------
// Last-report buffer
// ---------------------------------------------------------------------------
//
// We don't subscribe to the automation controller's full delegate chain
// (which runs async across multiple ticks). Instead we snapshot whatever the
// framework has accumulated when run_automation_specs returns. For the most
// recent invocation, get_last_test_report returns that snapshot.
//
// This is intentionally minimal: a richer integration would hook the
// IAutomationControllerModule events for per-it timings.

struct FLastReport
{
	bool bRan = false;
	FString Filter;
	int32 NumPass = 0;
	int32 NumFail = 0;
	double DurationSeconds = 0.0;
	TArray<TSharedPtr<FJsonValue>> Entries;
};

static FLastReport& GetLastReport()
{
	static FLastReport R;
	return R;
}

